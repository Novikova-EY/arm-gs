@dataclass(frozen=True)
class PdSummaryFormulaDef:
    key: str
    pages: frozenset[str]
    aggregation_level: str
    cell_name: str
    default_text: str

    def page_label_lines(self) -> tuple[str, ...]:
        if self.pages == ALL_SUMMARY_PAGES:
            return ("Все перечисленные сводки",)
        ordered = [PAGE_LABELS[p] for p in sorted(self.pages)]
        lines: list[str] = []
        for i, label in enumerate(ordered):
            lines.append(label + ";" if i < len(ordered) - 1 else label)
        return tuple(lines)

    def page_labels(self) -> str:
        return "\n".join(self.page_label_lines())


def _def(
    key: str,
    *,
    pages: frozenset[str] | None = None,
    aggregation_level: str,
    cell_name: str,
    default_text: str,
) -> PdSummaryFormulaDef:
    return PdSummaryFormulaDef(
        key=key,
        pages=pages or ALL_SUMMARY_PAGES,
        aggregation_level=aggregation_level,
        cell_name=cell_name,
        default_text=default_text.strip(),
    )


def _def_nt_pair(
    key_base: str,
    *,
    pages: frozenset[str],
    aggregation_level: str,
    cell_name: str,
    default_with_nt: str,
    default_without_nt: str,
) -> tuple[PdSummaryFormulaDef, PdSummaryFormulaDef]:
    return (
        _def(
            f"{key_base}_with_nt",
            pages=pages,
            aggregation_level=f"{aggregation_level} (с НТ)",
            cell_name=cell_name,
            default_text=default_with_nt,
        ),
        _def(
            f"{key_base}_without_nt",
            pages=pages,
            aggregation_level=f"{aggregation_level} (без НТ)",
            cell_name=cell_name,
            default_text=default_without_nt,
        ),
    )


