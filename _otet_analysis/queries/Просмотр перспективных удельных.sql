SELECT [Станции(Схема)].NAME, [Станции(Схема)].YEAR, [Станции(Схема)].E, IIf([E]>0,[ewtp]/[E],0) AS D_ewtp, IIf([Q]>0,[qotr]/[Q],0) AS D_otr, [Станции(Схема)].EURT, [Станции(Схема)].NUMB1120
FROM [Станции(Схема)]
WHERE ((([Станции(Схема)].YEAR)>2018))
ORDER BY [Станции(Схема)].numb1, [Станции(Схема)].YEAR;
