SELECT Имена_станций.NAME, Имена_станций.OES, Имена_станций.ordnumb, Имена_станций.NUMB
FROM Имена_станций INNER JOIN [Рабочий-для-ввода] ON Имена_станций.NUMB=[Рабочий-для-ввода].NUMB1120
WHERE (((Имена_станций.COMP)=1) AND (([Рабочий-для-ввода].VED)=0 Or ([Рабочий-для-ввода].VED) Is Null))
ORDER BY Имена_станций.OES, Имена_станций.ordnumb;
