SELECT [Станции(архив)].name, [Станции(архив)].year, [q]*[turt]/1000 AS bt, [Станции(архив)].tust, Abs([q]*[turt]/1000-[tust]) AS d
FROM [Станции(архив)]
WHERE ((([Станции(архив)].year)=2000 Or ([Станции(архив)].year)=2005 Or ([Станции(архив)].year)=2010) AND ((Abs([q]*[turt]/1000-[tust]))>1) AND (([Станции(архив)].oes)=5))
ORDER BY [Станции(архив)].numb1, [Станции(архив)].year;
