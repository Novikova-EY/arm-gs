SELECT [Доля промышленности].OES, Теплопотребление_АО.Name, ([лдцб]/[пром]*100) AS dлдцб, ([топл]/[пром]*100) AS dтопл, ([хнх]/[пром]*100) AS dхнх, (([чмет]+([цмет]))/[пром]*100) AS dмет
FROM [Доля промышленности] LEFT JOIN Теплопотребление_АО ON [Доля промышленности].Name=Теплопотребление_АО.Name
WHERE (((Теплопотребление_АО.год)="2004"))
ORDER BY [Доля промышленности].OES, Теплопотребление_АО.Name;
