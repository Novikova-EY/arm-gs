SELECT [Первое полугодие].[First-NAME], [Первое полугодие]![Sum-Q]/Год_режимы![Sum-Q]*100 AS D95, Имена_станций.GK
FROM ([Первое полугодие] INNER JOIN Год_режимы ON [Первое полугодие].NUMB=Год_режимы.NUMB) INNER JOIN Имена_станций ON [Первое полугодие].NUMB=Имена_станций.NUMB
WHERE (((Имена_станций.MAIN) Is Null));
