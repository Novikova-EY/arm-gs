def expand_sections(base: dict[str, list[str]], extra_paragraphs: dict[str, list[str]] | None = None) -> dict[str, list[str]]:
    """Добавляет абзацы для добора объема ~10 страниц на главу."""
    result = deepcopy(base)
    extra_paragraphs = extra_paragraphs or {}
    for k, v in extra_paragraphs.items():
        result.setdefault(k, [])
        result[k].extend(v)
    return result


