def write_module_chapter(doc, number: str, title: str, sections: dict[str, list[str]], bullets: dict[str, list[str]] | None = None):
    """sections: ключ = заголовок подраздела, значение = список абзацев."""
    bullets = bullets or {}
    add_heading_custom(doc, f"{number}. {title}", level=1)
    for i, sec_title in enumerate(SECTION_TITLES, start=1):
        add_heading_custom(doc, f"{number}.{i}. {sec_title}", level=2)
        for para in sections.get(sec_title, []):
            add_para(doc, para)
        if sec_title in bullets:
            add_bullets(doc, bullets[sec_title])
            add_para(doc, "")  # небольшой отступ после списка


