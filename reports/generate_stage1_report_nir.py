def _try_word_page_count(path: Path) -> int | None:
    try:
        import win32com.client  # type: ignore
    except Exception:
        return None
    word = None
    try:
        word = win32com.client.Dispatch("Word.Application")
        word.Visible = False
        wdoc = word.Documents.Open(str(path.resolve()))
        wdoc.Repaginate()
        pages = int(wdoc.ComputeStatistics(2))  # wdStatisticPages
        wdoc.Close(False)
        return pages
    except Exception as exc:  # noqa: BLE001
        print(f"WARN: Word page count unavailable: {exc}")
        return None
    finally:
        if word is not None:
            try:
                word.Quit()
            except Exception:
                pass


