def set_cell_text(cell, text: str) -> None:
    """Replace all paragraph text in a cell, keeping first paragraph style."""
    if not cell.paragraphs:
        cell.text = text
        return
    # Clear extra paragraphs
    for p in cell.paragraphs[1:]:
        p._element.getparent().remove(p._element)
    p = cell.paragraphs[0]
    # Clear runs
    for r in list(p.runs):
        r._element.getparent().remove(r._element)
    # Split by newlines into multiple paragraphs if needed
    lines = text.split("\n")
    p.add_run(lines[0])
    for line in lines[1:]:
        np = cell.add_paragraph(line)
        # copy pPr style from first if possible
        if p.style:
            np.style = p.style


def replace_unique_row_text(table, row_idx: int, new_text: str) -> None:
    """Set text for a logically unique (possibly merged) row."""
    row = table.rows[row_idx]
    seen = set()
    for cell in row.cells:
        cid = cell._tc
        if id(cid) in seen:
            continue
        seen.add(id(cid))
        set_cell_text(cell, new_text)


def clear_paragraph(paragraph) -> None:
    for r in list(paragraph.runs):
        r._element.getparent().remove(r._element)


def set_paragraph_text(paragraph, text: str) -> None:
    clear_paragraph(paragraph)
    paragraph.add_run(text)


def delete_body_after(doc: Document, keep_until_idx: int) -> None:
    """Delete body children after keep_until_idx, preserving sectPr."""
    body = doc.element.body
    children = list(body)
    for child in children[keep_until_idx + 1 :]:
        if child.tag == qn("w:sectPr"):
            continue
        body.remove(child)


def clear_paragraph_numbering(paragraph) -> None:
    """Убрать numPr у абзаца, чтобы стиль не тянул автонумерацию Word."""
    pPr = paragraph._p.get_or_add_pPr()
    for child in list(pPr):
        if child.tag == qn("w:numPr"):
            pPr.remove(child)


def add_styled(doc: Document, text: str, style: str):
    p = doc.add_paragraph(text, style=style)
    # Не наследовать автонумерацию Heading/Иллюстрация (иначе «1…1018» и «Ðèñóêîê»)
    if style != STYLE_BULLET:
        clear_paragraph_numbering(p)
    # Пустая строка после заголовков – интервал перед текстом раздела
    if style in (STYLE_H1, STYLE_H2, STYLE_STRUCT_TOC, STYLE_STRUCT_HIDDEN):
        blank = doc.add_paragraph()
        clear_paragraph_numbering(blank)
    return p


def add_page_break(doc: Document) -> None:
    p = doc.add_paragraph()
    run = p.add_run()
    run.add_break(WD_BREAK.PAGE)


def add_body_paras(doc: Document, paragraphs: list[str]) -> None:
    for text in paragraphs:
        if text.strip():
            add_styled(doc, text, STYLE_BODY)


def add_bullets(doc: Document, items: list[str]) -> None:
    for item in items:
        add_styled(doc, item, STYLE_BULLET)


class FigureCounter:
    def __init__(self) -> None:
        self.n = 0
        self.registry: dict[str, int] = {}

    def add_figure(self, doc: Document, stem: str, caption: str) -> int:
        path = SHOTS / f"{stem}.png"
        if not path.exists():
            add_styled(
                doc,
                f"[Рисунок не найден: {path.name}]",
                STYLE_BODY,
            )
            return 0
        self.n += 1
        self.registry[stem] = self.n
        # Пустая строка перед рисунком – интервал после предыдущего текста
        blank_before = doc.add_paragraph()
        clear_paragraph_numbering(blank_before)
        p = doc.add_paragraph()
        clear_paragraph_numbering(p)
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run()
        run.add_picture(str(path), width=Cm(16.0))
        # Подпись целиком в основном стиле (без автонумерации стиля «Иллюстрация»,
        # которая в части сред дает кракозябры «Ðèñóêîê» вместо «Рисунок»).
        cap = add_styled(
            doc,
            f"Рисунок {self.n}. {caption.lstrip()}",
            STYLE_BODY,
        )
        cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
        blank_after = doc.add_paragraph()
        clear_paragraph_numbering(blank_after)
        return self.n


def figure_ref_sentence(nums: list[int], lead: str) -> str:
    nums = [n for n in nums if n]
    if not nums:
        return ""
    if len(nums) == 1:
        return f"{lead} на рисунке {nums[0]}."
    joined = ", ".join(str(n) for n in nums[:-1]) + f" и {nums[-1]}"
    return f"{lead} на рисунках {joined}."


