def sanitize_document_artifacts(doc: Document) -> None:
    """Удаляет артефакты шаблона: англ. TOC-заглушки, «простыни» цифр,
    греческие буквы вместо кириллицы, типичные кракозябры."""
    import re

    en_toc = re.compile(
        r"^\s*(\d+\.?\s*)?(Introduction|Methodology|Results|Discussion|"
        r"Conclusion|Contents|References)\s*$",
        re.I,
    )
    en_toc_line = re.compile(
        r"(Introduction|Methodology|Results|Discussion|Conclusion)",
        re.I,
    )
    # «1. 2. 3. … 1018.» или сплошные цифры
    digit_sheet = re.compile(r"^[\d\s.,;:…\-\u2013\u2014]+$")
    numbered_run = re.compile(r"(?:\d+\.\s*){12,}")
    mojibake_ris = re.compile(r"Ð[èê].{0,6}[êê]")

    def fix_text(s: str) -> str:
        s = s.replace("\u0391", "\u0410").replace("\u03b1", "\u0430")
        s = s.replace("\u0395", "\u0415").replace("\u03b5", "\u0435")
        s = s.replace("\ufeff", "").replace("\ufffd", "")
        # типичный кракозябр «Рисунок» из cp1251→latin1
        if "Ðèñóêîê" in s or "Ðèñóíîê" in s or "Ðèñóêîê" in s:
            s = s.replace("Ðèñóêîê", "Рисунок").replace("Ðèñóíîê", "Рисунок")
            s = s.replace("Ðèñóêîê", "Рисунок")
        for bad, good in (
            ("Ðèñóêîê", "Рисунок"),
            ("Ðèñóíîê", "Рисунок"),
            ("â€“", "–"),
            ("â€”", "–"),
            ("â€™", "'"),
            ("Â«", "«"),
            ("Â»", "»"),
        ):
            if bad in s:
                s = s.replace(bad, good)
        return s

    to_remove = []
    for para in list(doc.paragraphs):
        clear_paragraph_numbering(para)
        raw = para.text
        text = raw.strip()
        if not text:
            continue
        if en_toc.match(text) or (
            en_toc_line.search(text)
            and len(text) < 120
            and not re.search(r"[А-Яа-яЁё]", text)
        ):
            to_remove.append(para)
            continue
        if numbered_run.search(text) and len(re.findall(r"\d+", text)) >= 15:
            to_remove.append(para)
            continue
        if len(text) > 60 and digit_sheet.match(text):
            digits = re.findall(r"\d+", text)
            if len(digits) >= 15:
                to_remove.append(para)
                continue
        if mojibake_ris.search(text) and len(text) < 30:
            # одиночная кракозябра-подпись без полезного текста
            to_remove.append(para)
            continue
        fixed = fix_text(raw)
        if fixed != raw:
            set_paragraph_text(para, fixed)

    for para in to_remove:
        el = para._element
        parent = el.getparent()
        if parent is not None:
            parent.remove(el)

    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for para in cell.paragraphs:
                    clear_paragraph_numbering(para)
                    raw = para.text
                    fixed = fix_text(raw)
                    if fixed != raw:
                        set_paragraph_text(para, fixed)


