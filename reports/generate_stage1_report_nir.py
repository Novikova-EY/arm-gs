def update_title_page(doc: Document) -> None:
    table = doc.tables[0]

    # R5: одна подпись УТВЕРЖДАЮ (без дублирования в объединенных ячейках)
    row = table.rows[5]
    seen: set[int] = set()
    target = None
    for cell in row.cells:
        cid = id(cell._tc)
        if cid in seen:
            continue
        seen.add(cid)
        if "Антонов" in cell.text or "____" in cell.text:
            target = cell
    if target is None:
        # правая (последняя уникальная) ячейка строки
        uniq = []
        seen.clear()
        for cell in row.cells:
            cid = id(cell._tc)
            if cid in seen:
                continue
            seen.add(cid)
            uniq.append(cell)
        target = uniq[-1] if uniq else None
    if target is not None:
        set_cell_text(
            target,
            "__________________ П.С. Антонов\n«___» _____________ 2026 г.",
        )
    # R6 stays: ОТЧЕТ по инновационному проекту
    replace_unique_row_text(table, 7, PROJECT_NAME)
    replace_unique_row_text(table, 8, STAGE_TITLE)
    replace_unique_row_text(
        table,
        9,
        "(промежуточный)\n\n\n"
        "Дирекция по развитию энергосистем\n"
        "Отдел генерации и прогнозирования спроса\n"
        "на электрическую энергию и мощность (НИО-10)\n"
        "Этап 1\n"
        "12.01.2026 – 30.09.2026\n",
    )

    # City/year paragraph and copyright: find by text
    for para in doc.paragraphs:
        t = para.text.replace("\xa0", " ")
        if t.startswith("Санкт-Петербург"):
            set_paragraph_text(para, "Санкт-Петербург 2026")
            para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        if t.startswith("©"):
            set_paragraph_text(para, "© АО «НТЦ ЕЭС», 2026")
            para.alignment = WD_ALIGN_PARAGRAPH.RIGHT


def estimate_page_count(doc: Document, n_figures: int) -> int:
    """Оценка числа страниц для строки реферата (без Word COM)."""
    chars = sum(len(p.text) for p in doc.paragraphs)
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                chars += len(cell.text)
    # Эмпирика NIR со скриншотами: титул/реферат/содержание ~10 с.;
    # рисунок с подписью ~0,9–1,2 с.; текст глав ~ chars/2400.
    pages = 10 + int(n_figures * 1.05) + chars // 2400
    return max(90, min(pages, 180))


def ensure_blank_after_template_headings(doc: Document) -> None:
    """Вставить пустую строку после заголовков из шаблона (РЕФЕРАТ и т.п.)."""
    targets = {"РЕФЕРАТ", "СПИСОК ИСПОЛНИТЕЛЕЙ"}
    # Iterate a snapshot of paragraphs; insert after matching ones
    for para in list(doc.paragraphs):
        if para.text.strip() not in targets:
            continue
        nxt = para._element.getnext()
        # Skip if next is already an empty paragraph
        if nxt is not None and nxt.tag == qn("w:p"):
            texts = [t.text or "" for t in nxt.iter(qn("w:t"))]
            if not "".join(texts).strip():
                continue
        blank = doc.add_paragraph()
        para._element.addnext(blank._element)


def update_referat(doc: Document, n_figures: int = 0, n_pages: int | None = None) -> None:
    """Update the three referat body paragraphs after РЕФЕРАТ heading."""
    found = False
    updated = 0
    pages_token = str(n_pages) if n_pages else "__"
    for para in doc.paragraphs:
        if para.text.strip() == "РЕФЕРАТ":
            found = True
            continue
        if not found:
            continue
        if para.style and para.style.name == STYLE_BODY and para.text.strip():
            if updated == 0:
                set_paragraph_text(
                    para,
                    f"Отчет {pages_token} с., 1 кн., 1 табл., {n_figures} рис., 2 прил.",
                )
            elif updated == 1:
                set_paragraph_text(para, KEYWORDS)
            elif updated == 2:
                set_paragraph_text(para, REFERAT_TEXT)
            updated += 1
            if updated >= 3:
                break


def add_compliance_table(doc: Document) -> None:
    table = doc.add_table(rows=1, cols=3)
    try:
        table.style = "Table Grid"
    except Exception:
        pass
    hdr = table.rows[0].cells
    hdr[0].text = "Задача этапа / требование"
    hdr[1].text = "Статус"
    hdr[2].text = "Доказательство (раздел / рисунок)"
    for req, status, proof in src.TZ_COMPLIANCE_ROWS:
        row = table.add_row().cells
        row[0].text = req
        row[1].text = status
        row[2].text = proof
    doc.add_paragraph()


