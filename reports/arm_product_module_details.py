def inject_details(
    chapters: list[tuple[str, str, dict[str, list[str]], str]],
) -> list[tuple[str, str, dict[str, list[str]], str]]:
    """Вставить предметный раздел перед методическими особенностями."""
    result: list[tuple[str, str, dict[str, list[str]], str]] = []
    for key, title, sections, figure_key in chapters:
        updated: dict[str, list[str]] = {}
        for section_title, paragraphs in sections.items():
            if section_title == "Методические особенности" and key in DETAILS:
                updated["Расчетные правила, входы и выходы"] = DETAILS[key]
            updated[section_title] = paragraphs
        result.append((key, title, updated, figure_key))
    return result
