def inject_detailed(
    chapters: list[tuple[str, str, dict[str, list[str]], str]],
) -> list[tuple[str, str, dict[str, list[str]], str]]:
    """Вставить дополнительное описание перед экранными формами."""
    out: list[tuple[str, str, dict[str, list[str]], str]] = []
    for key, title, sections, fig_key in chapters:
        new_sections: dict[str, list[str]] = {}
        for sec_title, paras in sections.items():
            if sec_title == "Экранные формы" and key in DETAILED:
                new_sections["Дополнительное описание текущей реализации"] = DETAILED[key]
            new_sections[sec_title] = paras
        out.append((key, title, new_sections, fig_key))
    return out
